package io.github.huydangtruong.permahearts.technique;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Set;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.core.particles.DustParticleOptions;
import net.minecraft.core.particles.ParticleTypes;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.sounds.SoundEvents;
import net.minecraft.sounds.SoundSource;
import net.minecraft.tags.BlockTags;
import net.minecraft.tags.FluidTags;
import net.minecraft.util.Mth;
import net.minecraft.world.level.ClipContext;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.levelgen.Heightmap;
import net.minecraft.world.phys.AABB;
import net.minecraft.world.phys.BlockHitResult;
import net.minecraft.world.phys.HitResult;
import net.minecraft.world.phys.Vec3;

/**
 * Thousand Mile Step (P-019, D58): the caster teleports far along the look direction, like an ender pearl that flies
 * {@code teleportRange(level) * charge} blocks. The look ray is cast through chunks that are already loaded only (nothing
 * is generated by the ray); a block hit becomes the landing spot. With no hit, the spot {@code d} blocks away horizontally is
 * loaded (one chunk) and the caster lands on its surface. Never void, blocks, lava or fire: then there is no cast.
 */
public final class ThousandMileStep {
	private static final double WIDTH = 0.6;
	private static final double HEIGHT = 1.8;
	/** How far the landing column may be moved sideways to find a safe spot (blocks, per axis). */
	private static final int SEARCH = 2;
	/** Distance between the chunk checks along the ray (a chunk is 16 wide). */
	private static final double RAY_STEP = 2.0;
	private static final int TRAIL_BLOCKS = 16;
	private static final List<int[]> OFFSETS = new ArrayList<>();

	static {
		for (int dx = -SEARCH; dx <= SEARCH; dx++) {
			for (int dz = -SEARCH; dz <= SEARCH; dz++) {
				OFFSETS.add(new int[] {dx, dz});
			}
		}
		OFFSETS.sort(Comparator.comparingInt(o -> o[0] * o[0] + o[1] * o[1]));
	}

	private ThousandMileStep() {}

	/** Casts it. False when there is no safe place to land (nothing happened, so no cooldown). */
	public static boolean cast(ServerPlayer p, int level, float charge) {
		ServerLevel sl = p.level();
		double d = OrbBallistics.chargedRange(TechniqueRules.teleportRange(level), charge);
		Vec3 dest = destination(sl, p, d);
		if (dest == null) {
			return false;
		}
		Vec3 from = p.position();
		p.stopRiding();
		if (!p.teleportTo(sl, dest.x, dest.y, dest.z, Set.of(), p.getYRot(), p.getXRot(), false)) {
			return false;
		}
		p.resetFallDistance(); // no fall damage from the step itself
		p.setDeltaMovement(Vec3.ZERO);
		effects(sl, from, dest);
		return true;
	}

	/** The safe standing spot (feet position) for a cast of reach d, or null. */
	static Vec3 destination(ServerLevel sl, ServerPlayer p, double d) {
		Vec3 eye = p.getEyePosition();
		Vec3 look = p.getViewVector(1f);
		double reach = loadedLength(sl, eye, look, d);
		if (reach > 0.5) {
			BlockHitResult hit = sl.clip(new ClipContext(eye, eye.add(look.scale(reach)), ClipContext.Block.COLLIDER, ClipContext.Fluid.NONE, p));
			if (hit.getType() == HitResult.Type.BLOCK) {
				return landAtHit(sl, hit);
			}
		}
		double yaw = Math.toRadians(p.getYRot());
		double tx = p.getX() - Math.sin(yaw) * d;
		double tz = p.getZ() + Math.cos(yaw) * d;
		return landOnSurface(sl, tx, tz, p.getY());
	}

	/** Length of the ray (at most d) that stays inside loaded chunks. */
	static double loadedLength(ServerLevel sl, Vec3 eye, Vec3 look, double d) {
		for (double t = 0; t <= d; t += RAY_STEP) {
			int cx = Mth.floor((eye.x + look.x * t)) >> 4;
			int cz = Mth.floor((eye.z + look.z * t)) >> 4;
			if (sl.getChunkSource().getChunkNow(cx, cz) == null) {
				return Math.max(0, t - RAY_STEP);
			}
		}
		return d;
	}

	// ---- landing ----

	private static Vec3 landAtHit(ServerLevel sl, BlockHitResult hit) {
		Vec3 h = hit.getLocation();
		Direction n = hit.getDirection();
		double x = h.x;
		double y = h.y;
		double z = h.z;
		switch (n) {
			case UP -> {}
			case DOWN -> y = h.y - HEIGHT - 0.01;
			default -> {
				x = h.x + n.getStepX() * (WIDTH / 2 + 0.05);
				z = h.z + n.getStepZ() * (WIDTH / 2 + 0.05);
				y = h.y - 1.0;
			}
		}
		return settle(sl, x, y, z);
	}

	private static Vec3 landOnSurface(ServerLevel sl, double tx, double tz, double playerY) {
		for (int[] o : OFFSETS) {
			double x = Mth.floor(tx) + o[0] + 0.5;
			double z = Mth.floor(tz) + o[1] + 0.5;
			if (!sl.getWorldBorder().isWithinBounds(x, z)) {
				continue;
			}
			sl.getChunk(Mth.floor(x) >> 4, Mth.floor(z) >> 4); // loads the one chunk (synchronous)
			Vec3 spot = sl.dimensionType().hasCeiling() ? scanColumn(sl, x, z, playerY) : surface(sl, x, z);
			if (spot != null) {
				return spot;
			}
		}
		return null;
	}

	/** Surface of a column under the open sky: on the top of the heightmap without leaves (water counts as ground). */
	private static Vec3 surface(ServerLevel sl, double x, double z) {
		int top = sl.getHeight(Heightmap.Types.MOTION_BLOCKING_NO_LEAVES, Mth.floor(x), Mth.floor(z));
		if (top <= sl.getMinY()) {
			return null;
		}
		for (int dy = 0; dy <= 3; dy++) {
			Vec3 spot = settle(sl, x, top + dy, z);
			if (spot != null) {
				return spot;
			}
		}
		return null;
	}

	/** Dimensions with a ceiling (the Nether): the roof is no place to land, so look for a free pocket near the caster's height. */
	private static Vec3 scanColumn(ServerLevel sl, double x, double z, double playerY) {
		int base = Mth.floor(playerY);
		for (int i = 0; i <= 128; i++) {
			for (int sign = -1; sign <= 1; sign += 2) {
				int y = base + i * sign;
				if (y < sl.getMinY() || y + HEIGHT > sl.getMaxY()) {
					continue;
				}
				if (fits(sl, x, y, z) && standsOnSolid(sl, x, y, z) && !unsafe(sl, x, y, z)) {
					return new Vec3(x, y, z);
				}
			}
		}
		return null;
	}

	/** From a rough feet position: free up to 2 blocks, then falls to the ground. Null when there is no safe standing spot. */
	private static Vec3 settle(ServerLevel sl, double x, double y, double z) {
		double sy = y;
		for (int up = 0; up <= 2 && !fits(sl, x, sy, z); up++) {
			sy = y + up + 1;
		}
		if (!fits(sl, x, sy, z)) {
			return null;
		}
		for (int i = 0; i < 400; i++) {
			if (sy < sl.getMinY()) {
				return null; // void
			}
			if (supported(sl, x, sy, z)) {
				return unsafe(sl, x, sy, z) ? null : new Vec3(x, sy, z);
			}
			if (fits(sl, x, sy - 1, z)) {
				sy -= 1;
				continue;
			}
			double fine = sy;
			for (int k = 0; k < 20 && fits(sl, x, fine - 0.05, z); k++) {
				fine -= 0.05;
			}
			return supported(sl, x, fine, z) && !unsafe(sl, x, fine, z) ? new Vec3(x, fine, z) : null;
		}
		return null;
	}

	// ---- tests of a spot ----

	private static AABB box(double x, double y, double z) {
		return new AABB(x - WIDTH / 2, y, z - WIDTH / 2, x + WIDTH / 2, y + HEIGHT, z + WIDTH / 2);
	}

	private static boolean fits(ServerLevel sl, double x, double y, double z) {
		return y >= sl.getMinY() && y + HEIGHT <= sl.getMaxY() + 1 && sl.noCollision(box(x, y, z));
	}

	private static boolean standsOnSolid(ServerLevel sl, double x, double y, double z) {
		return !sl.noCollision(box(x, y - 0.05, z).setMaxY(y));
	}

	/** Standing on something: a block, or water (the caster lands in it). */
	private static boolean supported(ServerLevel sl, double x, double y, double z) {
		return standsOnSolid(sl, x, y, z) || sl.getFluidState(BlockPos.containing(x, y - 0.05, z)).is(FluidTags.WATER);
	}

	/** Lava, fire or a damaging block around the spot or under it. */
	private static boolean unsafe(ServerLevel sl, double x, double y, double z) {
		AABB b = box(x, y - 0.1, z).inflate(0.1, 0, 0.1);
		for (int bx = Mth.floor(b.minX); bx <= Mth.floor(b.maxX); bx++) {
			for (int by = Mth.floor(b.minY); by <= Mth.floor(b.maxY); by++) {
				for (int bz = Mth.floor(b.minZ); bz <= Mth.floor(b.maxZ); bz++) {
					BlockState s = sl.getBlockState(new BlockPos(bx, by, bz));
					if (s.getFluidState().is(FluidTags.LAVA) || s.is(BlockTags.FIRE) || s.is(BlockTags.CAMPFIRES)
						|| s.is(Blocks.MAGMA_BLOCK) || s.is(Blocks.CACTUS) || s.is(Blocks.SWEET_BERRY_BUSH) || s.is(Blocks.POWDER_SNOW)) {
						return true;
					}
				}
			}
		}
		return false;
	}

	// ---- effects ----

	private static void effects(ServerLevel sl, Vec3 from, Vec3 to) {
		DustParticleOptions violet = new DustParticleOptions(0x9a3cff, 1.2f);
		burst(sl, from, violet);
		sl.playSound(null, BlockPos.containing(from), SoundEvents.ENDERMAN_TELEPORT, SoundSource.PLAYERS, 1f, 1f);
		Vec3 dir = to.subtract(from);
		double len = dir.length();
		if (len > 0.5) {
			Vec3 step = dir.scale(1 / len);
			for (int i = 1; i <= Math.min(TRAIL_BLOCKS, (int) len); i++) {
				Vec3 at = from.add(step.scale(i)).add(0, 1, 0);
				sl.sendParticles(ParticleTypes.PORTAL, at.x, at.y, at.z, 4, 0.2, 0.3, 0.2, 0.2);
				sl.sendParticles(violet, at.x, at.y, at.z, 1, 0.1, 0.1, 0.1, 0.0);
			}
		}
		burst(sl, to, violet);
		sl.playSound(null, BlockPos.containing(to), SoundEvents.CHORUS_FRUIT_TELEPORT, SoundSource.PLAYERS, 1f, 1f);
		sl.playSound(null, BlockPos.containing(to), SoundEvents.ENDERMAN_TELEPORT, SoundSource.PLAYERS, 0.8f, 1.2f);
	}

	private static void burst(ServerLevel sl, Vec3 at, DustParticleOptions violet) {
		sl.sendParticles(ParticleTypes.PORTAL, at.x, at.y + 1, at.z, 60, 0.4, 0.8, 0.4, 0.8);
		sl.sendParticles(violet, at.x, at.y + 1, at.z, 20, 0.4, 0.8, 0.4, 0.02);
	}
}
